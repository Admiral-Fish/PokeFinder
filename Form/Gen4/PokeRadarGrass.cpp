static const RadarGrassFieldData *getRadarGrassFieldData(u16 location, u8 occurrence, Game version)
{
    for (const auto &field : radarGrassFields)
    {
        if (field.location == location && field.occurrence == occurrence && (field.version & version) != Game::None)
        {
            return &field;
        }
    }

    return nullptr;
}

QSize getPokeRadarGrassFieldSize(u16 location, u8 occurrence, Game version)
{
    if (const RadarGrassFieldData *field = getRadarGrassFieldData(location, occurrence, version); field != nullptr)
    {
        return QSize(field->width, field->height);
    }

    return QSize(9, 9);
}

std::vector<bool> getPokeRadarGrassField(u16 location, u8 occurrence, Game version)
{
    if (const RadarGrassFieldData *data = getRadarGrassFieldData(location, occurrence, version); data != nullptr)
    {
        std::vector<bool> field(data->width * data->height);
        for (size_t i = 0; i < field.size(); i++)
        {
            field[i] = data->tiles[i] == '#';
        }
        return field;
    }

    QSize size = getPokeRadarGrassFieldSize(location, occurrence, version);
    return std::vector<bool>(size.width() * size.height(), true);
}

QPoint getPokeRadarGrassFieldStart(u16 location, u8 occurrence, Game version)
{
    if (const RadarGrassFieldData *field = getRadarGrassFieldData(location, occurrence, version); field != nullptr)
    {
        return QPoint(field->startX, field->startY);
    }

    QSize size = getPokeRadarGrassFieldSize(location, occurrence, version);
    return QPoint(size.width() / 2, size.height() / 2);
}

